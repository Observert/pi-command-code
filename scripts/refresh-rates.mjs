/**
 * Regenerates the bundled rate table in rates.ts from Command Code's published
 * pricing table.
 *
 * Why a build-time script instead of a runtime fetch: the pricing table lives
 * in the docs page HTML (server-rendered `<div role="row">` cells), and parsing
 * HTML at every pi startup would be slow and would break the moment the docs
 * markup changes. Running it here keeps startup pure-JSON and lets a human
 * review the diff.
 *
 *   node scripts/refresh-rates.mjs          # rewrite rates.ts
 *   node scripts/refresh-rates.mjs --check  # exit 1 if rates.ts is stale
 *
 * Rates are USD per million tokens, taken from:
 *   https://commandcode.ai/docs/resources/pricing-limits  ("Model pricing. At cost.")
 *
 * The table lists DISPLAY NAMES, so this script maps them onto the live API
 * model ids from /provider/v1/models by exact name match. Models in the table
 * that are no longer in the API catalog are dropped, and any catalog model with
 * no pricing row is reported so the gap is visible rather than silent.
 */

import { writeFileSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const PRICING_URL = "https://commandcode.ai/docs/resources/pricing-limits";
const CATALOG_URL = "https://api.commandcode.ai/provider/v1/models";
const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "rates.ts");

const stripTags = (s) =>
  s
    .replace(/<!-- -->/g, "")
    .replace(/<[^>]+>/g, "")
    .replace(/&amp;/g, "&")
    .replace(/&mdash;/g, "-")
    .trim();

/** "$3.00" -> 3, "Free" -> 0, "-"/"—" -> null (not offered). */
function parseRate(cell) {
  const c = cell.trim();
  if (/^free$/i.test(c)) return 0;
  if (c === "-" || c === "—" || c === "") return null;
  // Discounted cells render as "$0.60$0.30" (was -> now). Take the LAST value:
  // that is the price you actually pay today.
  const money = [...c.matchAll(/\$([0-9]+(?:\.[0-9]+)?)/g)];
  if (money.length === 0) return null;
  return Number.parseFloat(money[money.length - 1][1]);
}

async function fetchPricingTable() {
  const res = await fetch(PRICING_URL, {
    headers: { "User-Agent": "Mozilla/5.0" },
  });
  if (!res.ok) throw new Error(`pricing page: HTTP ${res.status}`);
  const html = await res.text();

  const rows = [];
  for (const seg of html.split('role="row"').slice(1)) {
    const body = seg.split("</div></div></div>")[0];
    const cells = [
      ...body.matchAll(
        /<div class="[^"]*(?:px-\d|truncate)[^"]*"[^>]*>([\s\S]*?)<\/div>/g,
      ),
    ].map((c) => stripTags(c[1]));

    const rates = cells.filter((c) => /^\$|^Free$|^[-—]$/.test(c));
    if (cells.length < 5 || rates.length < 3) continue;

    // Cell order: name, context, input, output, cacheRead, cacheWrite, caps
    const name = cells[0]
      .replace(/FREE$/i, "")
      .replace(/-\d+%$/, "")
      .trim();
    const input = parseRate(cells[2]);
    const output = parseRate(cells[3]);
    if (input === null || output === null) continue;

    rows.push({
      name,
      input,
      output,
      cacheRead: parseRate(cells[4]) ?? 0,
      cacheWrite: parseRate(cells[5]) ?? 0,
    });
  }
  return rows;
}

async function fetchCatalog() {
  const res = await fetch(CATALOG_URL, {
    headers: { "User-Agent": "Mozilla/5.0" },
  });
  if (!res.ok) throw new Error(`catalog: HTTP ${res.status}`);
  const payload = await res.json();
  if (!Array.isArray(payload?.data))
    throw new Error("catalog: unexpected shape");
  return payload.data;
}

function render(entries) {
  const lines = entries
    .map(({ id, input, output, cacheRead, cacheWrite }) => {
      const rates = [input, output, cacheRead, cacheWrite].join(", ");
      return `  ["${id}", { input: ${input}, output: ${output}, cacheRead: ${cacheRead}, cacheWrite: ${cacheWrite} }],`;
    })
    .join("\n");

  return `/**
 * Command Code per-model rates, in USD per million tokens.
 *
 * GENERATED by scripts/refresh-rates.mjs — do not edit by hand.
 * Source: ${PRICING_URL}
 * ("Model pricing. At cost.", mapped onto live model ids from /provider/v1/models)
 *
 * Refresh with:
 *
 *   node scripts/refresh-rates.mjs
 *
 * These are published list rates. A given request can cost slightly less,
 * because Command Code routes open-source models across multiple upstreams and
 * bills the mean per-provider price; live deals (free tiers, discounts) are
 * already reflected here as of the generation date. Your Command Code Usage page
 * remains the source of truth, especially under ZDR where pass-through rates
 * can differ.
 */
export const RATE_CARDS: Array<[string, { input: number; output: number; cacheRead: number; cacheWrite: number }]> = [
${lines}
];
`;
}

async function main() {
  const check = process.argv.includes("--check");

  const [pricing, catalog] = await Promise.all([
    fetchPricingTable(),
    fetchCatalog(),
  ]);
  const nameToId = new Map(catalog.map((m) => [m.name, m.id]));

  const entries = [];
  const missing = [];
  for (const row of pricing) {
    const id = nameToId.get(row.name);
    if (!id) continue; // pricing row for a model no longer offered
    entries.push({ id, ...row });
  }
  for (const m of catalog) {
    if (!pricing.some((p) => p.name === m.name)) missing.push(m.name);
  }

  entries.sort((a, b) => a.id.localeCompare(b.id));

  const next = render(entries);
  const prev = (() => {
    try {
      return readFileSync(OUT, "utf8");
    } catch {
      return "";
    }
  })();

  console.error(
    `pricing rows: ${pricing.length} | catalog: ${catalog.length} | matched: ${entries.length}`,
  );
  if (missing.length) {
    console.error(
      `WARNING: ${missing.length} catalog model(s) have no pricing row:`,
    );
    console.error("  " + missing.join("\n  "));
  }

  if (check) {
    if (prev === next) {
      console.error("rates.ts is up to date");
      return;
    }
    console.error("rates.ts is STALE — run: node scripts/refresh-rates.mjs");
    process.exit(1);
  }

  writeFileSync(OUT, next);
  console.error(`wrote ${OUT} (${entries.length} models)`);
}

await main();
